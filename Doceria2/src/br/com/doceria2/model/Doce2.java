package br.com.doceria2.model;

public class Doce2 
{
	private String tituloDoce;
	private double valordoce;
	private String marca;
	
	
	public String getTituloDoce() {
		return tituloDoce;
	}
	public void setTituloDoce(String tituloDoce) {
		this.tituloDoce = tituloDoce;
	}
	public double getValordoce() {
		return valordoce;
	}
	public void setValordoce(double valordoce) {
		this.valordoce = valordoce;
	}
	public String getMarca() {
		return marca;
	}
	public void setMarca(String marca) {
		this.marca = marca;
	}
}
